import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

// Keep complete upstream texts in one redistributable file, without publishing
// internal approval records or a duplicate directory of dependency licences.
const tree = JSON.parse(
  execFileSync("pnpm", ["list", "--prod", "--depth", "Infinity", "--json"], {
    encoding: "utf8",
  }),
);
const packages = new Map();
function visit(deps) {
  for (const dep of Object.values(deps ?? {})) {
    if (dep.path) {
      const pkg = JSON.parse(
        readFileSync(join(dep.path, "package.json"), "utf8"),
      );
      const id = `${pkg.name}@${pkg.version}`;
      if (packages.has(id)) continue;
      packages.set(id, { path: dep.path, pkg });
    }
    visit(dep.dependencies);
    visit(dep.optionalDependencies);
  }
}
for (const root of tree) {
  visit(root.dependencies);
  visit(root.optionalDependencies);
}
function files(path, prefix = "") {
  return readdirSync(path)
    .sort()
    .flatMap((name) => {
      const full = join(path, name);
      const label = prefix + name;
      return statSync(full).isDirectory()
        ? files(full, label + "/")
        : [{ name: label, text: readFileSync(full, "utf8") }];
    });
}
let output = `# Third-party notices

Ingestron core is licensed by Otrera Limited under Apache-2.0. Third-party
material retains the following licences and notices.

## Bundled assets

- ODCS schema: see \`schemas/ODCS-LICENSE\` and \`schemas/provenance.json\`.
- Meltano catalogue metadata: see \`catalogue/MELTANO-LICENSE.txt\` and
  \`catalogue/NOTICE.txt\`. Individual connectors have their own licences.

These asset files are also included under \`dist/assets/\` in the npm package.

## Production dependencies

Generated by \`pnpm licences:inventory\` from the installed production dependency
tree. Dependency implementations are installed separately by npm; their upstream
licence and notice texts are reproduced below for reference.
`;
assert.ok(
  packages.size,
  "Install production dependencies before generating notices",
);
for (const [id, { path, pkg }] of [...packages].sort(([a], [b]) =>
  a.localeCompare(b),
)) {
  assert.ok(
    pkg.license && pkg.license !== "UNLICENSED",
    `Review licence for ${id}`,
  );
  const notices = readdirSync(path)
    .sort()
    .filter((n) => /^(licen[sc]e|copying|notice)([.-].*)?$/i.test(n))
    .flatMap((name) => {
      const full = join(path, name);
      return statSync(full).isDirectory()
        ? files(full, name + "/")
        : [{ name, text: readFileSync(full, "utf8") }];
    });
  assert.ok(notices.length, `Missing upstream notices for ${id}`);
  output += `\n### ${id}\n\nDeclared licence: ${pkg.license}\n`;
  for (const notice of notices) {
    // Fence safely even if an upstream text contains Markdown fences.
    const fence = "`".repeat(
      Math.max(
        3,
        ...[...notice.text.matchAll(/`+/g)].map((m) => m[0].length + 1),
      ),
    );
    output += `\n${notice.name}:\n\n${fence}text\n${notice.text}${notice.text.endsWith("\n") ? "" : "\n"}${fence}\n`;
  }
}
if (process.argv.includes("--check")) {
  assert.equal(
    readFileSync("THIRD_PARTY_NOTICES.md", "utf8"),
    output,
    "Dependency notices are stale; run pnpm licences:inventory and review the changes",
  );
} else {
  writeFileSync("THIRD_PARTY_NOTICES.md", output);
}
console.log(
  `${packages.size} production dependency notices ${process.argv.includes("--check") ? "verified" : "generated"}`,
);
